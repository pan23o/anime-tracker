const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const html = fs.readFileSync('index.html', 'utf8');
const start = html.indexOf('function applyAniData(');
const end = html.indexOf('\nasync function lookupWikipedia', start);
assert.ok(start >= 0 && end > start, 'Episode update function must exist');
const context = { Date, Number, Math, String, Array };
vm.createContext(context);
vm.runInContext(html.slice(start, end), context);
const media = episodes => ({ id: 1, title: { romaji: 'Example' }, episodes, status: 'FINISHED' });
const item = { anime: 'Example', total: '220', knownTotal: '220', plannedEpisodes: '220', watched: '205' };
context.applyAniData(item, media(170));
assert.equal(item.total, '220');
assert.equal(item.watched, '205');
context.applyAniData(item, media(240));
assert.equal(item.total, '240');
assert.equal(item.watched, '205');
const restored = { anime: 'Example', total: '170', knownTotal: '170', watched: '180' };
context.applyAniData(restored, media(170));
assert.equal(restored.total, '180');
assert.equal(restored.watched, '180');
const rows = [{ anime: 'Example', total: '170', knownTotal: '220', watched: '180', state: 'viendo' }, { anime: 'Another', total: '170', watched: '180', state: 'viendo' }];
const completeContext = { data: rows, window: { addEventListener() {}, render() {} }, document: { readyState: 'complete', getElementById() { return null; } }, save() {}, console, Date, Number, Math, String, Array };
vm.createContext(completeContext);
vm.runInContext(fs.readFileSync('onebase-auto-complete.js', 'utf8'), completeContext);
assert.equal(rows[0].state, 'viendo');
assert.equal(rows[1].watched, '180');
console.log('Episode updates preserve progress and reconcile totals.');
